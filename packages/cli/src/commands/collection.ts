import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCommandArgs } from "../args.ts";
import { CliError, type CliIo } from "../errors.ts";
import { outputTail, resolveWorkerDir } from "../worker-target.ts";

// Laravel's make:model -m and model:show for Takebase collections.

const usage = "takebase collection <create|inspect> <name> [options]";

const help = `Generate and inspect collections in one Worker.

Usage: ${usage}

Commands:
  create <name> --field <name:type[?]>...  Write src/schema/<name>.ts and src/collections/<name>.ts
  inspect <name>                           Show a registered collection's columns, rules, validation, filters and hooks

Options:
  --field <name:type[?]>  A column; type is text, integer, real or boolean, "?" makes it nullable (repeatable)
  --worker <dir>          Worker directory with wrangler.jsonc (default: the current directory)
  -h, --help              Show this help

Generated collections have no rules, so every operation is denied until you add one.
`;

const options = {
	field: { type: "string", multiple: true },
	worker: { type: "string" },
	help: { type: "boolean", short: "h" },
} as const;

const namePattern = /^[a-z][a-z0-9_]{0,62}$/;
const serverOwned = ["id", "created", "updated"];

const fieldTypes = {
	text: { column: "text", rule: "string" },
	integer: { column: "integer", rule: "integer" },
	real: { column: "real", rule: "numeric" },
	boolean: { column: "integer", rule: "boolean" },
} as const;

type FieldType = keyof typeof fieldTypes;
type Field = { name: string; type: FieldType; nullable: boolean };

const usageError = (message: string, hint = `Usage: ${usage}`) => new CliError(message, { usage: true, hint });

const parseField = (spec: string): Field => {
	const match = /^([a-z][a-z0-9_]{0,62}):([a-z]+)(\?)?$/.exec(spec);
	const type = match?.[2];
	if (!match || type === undefined || !Object.hasOwn(fieldTypes, type)) {
		throw usageError(
			`Invalid --field "${spec}"`,
			"Use name:type with type text, integer, real or boolean, e.g. --field premium:integer?",
		);
	}
	const name = match[1] ?? "";
	if (serverOwned.includes(name)) throw usageError(`Field "${name}" is added by id() and timestamps()`);
	return { name, type: type as FieldType, nullable: match[3] === "?" };
};

const camelCase = (name: string) => name.replace(/_([a-z0-9])/g, (_, char: string) => char.toUpperCase());

const columnCode = ({ name, type, nullable }: Field) => {
	const options = type === "boolean" ? `, { mode: "boolean" }` : "";
	return `\t${name}: ${fieldTypes[type].column}("${name}"${options})${nullable ? "" : ".notNull()"},`;
};

const schemaSource = (name: string, fields: Field[]) => {
	const imports = [...new Set(["sqliteTable", ...fields.map((field) => fieldTypes[field.type].column)])].sort();
	return `import { id, timestamps } from "@takebase/core";
import { ${imports.join(", ")} } from "drizzle-orm/sqlite-core";

// Generated by \`takebase collection create\`. Run \`takebase migrate generate\` after changing it.
export const ${camelCase(name)} = sqliteTable("${name}", {
\t...id(),
${fields.map(columnCode).join("\n")}
\t...timestamps(),
});
`;
};

const collectionSource = (name: string, fields: Field[]) => `import { defineCollection } from "@takebase/core";
import { ${camelCase(name)} } from "../schema/${name}.ts";

// Generated by \`takebase collection create\`. There are no rules yet, so every
// operation is denied; add list/view/create/update/delete rules to open it.
export const ${camelCase(name)}Collection = defineCollection({
\ttable: ${camelCase(name)},
\trules: {},
\tvalidate: {
${fields.map((field) => `\t\t${field.name}: "${field.nullable ? "nullable" : "required"}|${fieldTypes[field.type].rule}",`).join("\n")}
\t},
});
`;

const create = (io: CliIo, dir: string, name: string, specs: string[]) => {
	if (specs.length === 0) throw usageError("collection create needs at least one --field");
	const fields = specs.map(parseField);
	const duplicate = fields.find((field, index) => fields.findIndex((other) => other.name === field.name) !== index);
	if (duplicate) throw usageError(`Field "${duplicate.name}" is given twice`);

	const files = [
		[join(dir, "src", "schema", `${name}.ts`), schemaSource(name, fields)],
		[join(dir, "src", "collections", `${name}.ts`), collectionSource(name, fields)],
	] as const;
	const existing = files.filter(([path]) => existsSync(path)).map(([path]) => relative(io.cwd, path));
	if (existing.length > 0) {
		throw new CliError(`Refusing to overwrite ${existing.join(", ")}`, {
			hint: "Choose another name or edit the files.",
		});
	}
	for (const [path, source] of files) {
		mkdirSync(join(path, ".."), { recursive: true });
		writeFileSync(path, source, { flag: "wx" });
	}
	io.stdout(
		`Created collection "${name}":\n${files.map(([path]) => `  ${relative(io.cwd, path)}`).join("\n")}\n\n` +
			`Next steps:\n  1. Register ${camelCase(name)}Collection in src/collections/index.ts\n` +
			"  2. Add rules; every operation is denied until you do\n" +
			`  3. takebase migrate generate --name create_${name}\n  4. takebase migrate apply\n`,
	);
	return 0;
};

type Described = {
	name: string;
	table: string;
	columns: { field: string; type: string; notNull: boolean; primaryKey: boolean; unique: boolean }[];
	rules: Record<string, string>;
	validation: Record<string, string>;
	filters: Record<string, string[]>;
	sorts: string[];
	hooks: string[];
};

const loader = fileURLToPath(new URL("../collection-loader.ts", import.meta.url));

const table = (rows: string[][]) => {
	const widths = rows[0]?.map((_, column) => Math.max(...rows.map((row) => (row[column] ?? "").length))) ?? [];
	return rows
		.map(
			(row) =>
				`  ${row
					.map((cell, column) => cell.padEnd(widths[column] ?? 0))
					.join("  ")
					.trimEnd()}`,
		)
		.join("\n");
};

const format = (collection: Described) => {
	const columns = collection.columns.map((column) => [
		column.field,
		column.type,
		[
			column.primaryKey ? "primary key" : "",
			column.notNull && !column.primaryKey ? "not null" : "",
			column.unique ? "unique" : "",
		]
			.filter((flag) => flag !== "")
			.join(", "),
		collection.validation[column.field] ?? (serverOwned.includes(column.field) ? "(server-owned)" : "(not writable)"),
	]);
	const filters = Object.entries(collection.filters).map(([field, operators]) => `${field} (${operators.join(", ")})`);
	return `Collection ${collection.name} (table ${collection.table})

Columns:
${table([["field", "type", "constraints", "validation"], ...columns])}

Rules:
${table(Object.entries(collection.rules))}

Filters: ${filters.length > 0 ? filters.join(", ") : "none"}
Sorts:   ${collection.sorts.length > 0 ? collection.sorts.join(", ") : "none"}
Hooks:   ${collection.hooks.length > 0 ? collection.hooks.join(", ") : "none"}
`;
};

const inspect = (io: CliIo, dir: string, name: string) => {
	const registryModule = join(dir, "src", "collections", "index.ts");
	if (!existsSync(registryModule)) {
		throw new CliError(`No ${relative(io.cwd, registryModule)}`, {
			hint: "collection inspect reads the registry exported from src/collections/index.ts.",
		});
	}
	const result = spawnSync(process.execPath, [loader, registryModule, name], {
		cwd: dir,
		encoding: "utf8",
		stdio: ["ignore", "pipe", "pipe"],
		timeout: 60_000,
	});
	let output: { collection?: Described; error?: string; names?: string[] } | undefined;
	try {
		output = result.status === 0 ? JSON.parse(result.stdout) : undefined;
	} catch {
		output = undefined;
	}
	if (!output)
		throw new CliError(`Could not load ${relative(io.cwd, registryModule)}:\n${outputTail(result.stderr ?? "")}`);
	if (output.error === "no-registry") {
		throw new CliError(`${relative(io.cwd, registryModule)} exports no collection registry`, {
			hint: "Export the result of createCollectionRegistry([...]).",
		});
	}
	if (!output.collection) {
		throw new CliError(`Collection "${name}" is not registered`, {
			hint: `Registered: ${output.names?.join(", ") || "none"}`,
		});
	}
	io.stdout(format(output.collection));
	return 0;
};

export const collectionCommand = (args: string[], io: CliIo) => {
	const { values, positionals } = parseCommandArgs("collection", args, options);
	if (values.help === true) {
		io.stdout(help);
		return 0;
	}
	const [subcommand, name, ...extra] = positionals;
	if (subcommand === undefined) throw usageError("Missing collection command");
	if (subcommand !== "create" && subcommand !== "inspect")
		throw usageError(`Unknown collection command "${subcommand}"`);
	if (name === undefined) throw usageError("Missing collection name");
	if (!namePattern.test(name)) {
		throw usageError(
			`Invalid collection name "${name}"`,
			"Use lowercase letters, digits and underscores, starting with a letter.",
		);
	}
	if (extra.length > 0) throw usageError(`Unexpected arguments: ${extra.join(" ")}`);
	const dir = resolveWorkerDir(io.cwd, values.worker);
	if (subcommand === "create") return create(io, dir, name, values.field ?? []);
	if (values.field !== undefined) throw usageError("--field is only for collection create");
	return inspect(io, dir, name);
};
